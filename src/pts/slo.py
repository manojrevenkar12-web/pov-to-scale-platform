"""Generate Prometheus multi-window, multi-burn-rate alert rules from config/slo.yaml."""

from __future__ import annotations

from typing import Any

import yaml

from . import config


def ratio(expr_good: str, expr_total: str, window: str) -> str:
    return f"1 - ({expr_good.replace('{{window}}', window)}) / ({expr_total.replace('{{window}}', window)})"


def rules(cfg: dict[str, Any] | None = None) -> dict[str, Any]:
    c = cfg or config.load("slo")
    groups = []
    for o in c["objectives"]:
        budget = round(1 - o["target"], 6)
        windows = sorted({w for a in c["alerts"] for w in (a["long"], a["short"])}, key=_seconds)
        recording = [
            {
                "record": f"engagement:slo_{o['name']}_error_ratio:rate{w}",
                "expr": ratio(o["good"], o["total"], w),
            }
            for w in windows
        ]
        alerts = []
        for a in c["alerts"]:
            threshold = round(a["burn"] * budget, 6)
            alerts.append(
                {
                    "alert": f"SLO{o['name'].title()}Burn{a['long']}",
                    "expr": (
                        f"engagement:slo_{o['name']}_error_ratio:rate{a['long']} > {threshold} "
                        f"and engagement:slo_{o['name']}_error_ratio:rate{a['short']} > {threshold}"
                    ),
                    "labels": {"severity": a["severity"], "slo": o["name"]},
                    "annotations": {
                        "summary": f"{{{{ $labels.engagement }}}} burns the {o['name']} error budget "
                        f"{a['burn']}x too fast",
                        "runbook_url": f"runbooks/slo-{o['name']}.md",
                    },
                }
            )
        groups.append({"name": f"slo-{o['name']}", "rules": recording + alerts})
    return {"groups": groups}


def _seconds(w: str) -> int:
    return int(w[:-1]) * {"m": 60, "h": 3600, "d": 86400}[w[-1]]


def render(cfg: dict[str, Any] | None = None) -> str:
    head = "# Generated by `pts slo-rules` from config/slo.yaml. Do not edit by hand.\n"
    return head + yaml.safe_dump(rules(cfg), sort_keys=False, width=200)
